
type HeaderBarProps = {
  darkMode: boolean
  onToggleTheme: () => void
}

export function HeaderBar({ darkMode, onToggleTheme }: HeaderBarProps) {
    return (
      <header className="header-bar">
        <div className="header-bar__content">
          <span className="header-bar__title">Substation Device Monitoring</span>
        </div>

        <ThemeToggle
          darkMode={darkMode}
          onToggleTheme={onToggleTheme}
        />
      </header>
    )
}

// ThemeToggle takes the HeaderBarProps to stay in sync with HeaderBar.
// However the header bar keeps its color regardless of light or dark mode.
function ThemeToggle({ darkMode, onToggleTheme }: HeaderBarProps) {
  return (
    <button
      type="button"
      onClick={onToggleTheme}
      className="theme-toggle"
      aria-label={darkMode ? 'Switch to light mode' : 'Switch to dark mode'}
    >
      <svg
        viewBox="0 0 12 12"
        width="12"
        height="12"
        aria-hidden="true"
        focusable="false"
      >
        {darkMode ? (
          // Sun SVG (Generated by AI)
          <path
            d="M6 1v1m0 8v1M1 6h1m8 0h1M2.46 2.46l.7.7m5.68 5.68.7.7m0-7.08-.7.7M3.16 8.84l-.7.7M6 3.5a2.5 2.5 0 1 0 0 5 2.5 2.5 0 0 0 0-5Z"
            fill="none"
            stroke="currentColor"
            strokeLinecap="round"
            strokeLinejoin="round"
            strokeWidth="2"
          />
        ) : (
          // Moon SVG (Generated by AI)
          <path
            d="M9.8 7.8A4.2 4.2 0 0 1 4.2 2.2 4.2 4.2 0 1 0 9.8 7.8Z"
            fill="none"
            stroke="currentColor"
            strokeLinecap="round"
            strokeLinejoin="round"
            strokeWidth="2"
          />
        )}
      </svg>
    </button>
  )
}

export default HeaderBar